#!/usr/bin/env python
"""Render the stratified external review sample as an Excel workbook.

Input: ``runs/external_cq/review_sample.csv`` (generated by
``eval/plan_external_review.py``).  The reviewer fills only the manual columns;
the per-scene precision estimate and auto-adoption decision are computed after
the workbook is returned.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation

HEADER_FILL = PatternFill("solid", fgColor="1F4E79")
HEADER_FONT = Font(color="FFFFFF", bold=True)
MANUAL_FILL = PatternFill("solid", fgColor="DDEBF7")
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
WRAP = Alignment(wrap_text=True, vertical="top")

COLUMNS = [
    ("序号", 6), ("场景", 22), ("agent结果", 42), ("agent置信度", 11),
    ("probe_P涉诈", 11), ("来源文件", 38), ("source_date", 12), ("callid", 22),
    ("内容", 100), ("复核_is_fraud", 12), ("复核_scene", 22),
    ("复核_subtype", 20), ("复核依据", 40), ("复核人", 10), ("复核日期", 12),
]
MANUAL = {"复核_is_fraud", "复核_scene", "复核_subtype", "复核依据", "复核人", "复核日期"}


def safe(value: str) -> str:
    text = value or ""
    if text and text[0] in "=+-@":
        text = "'" + text
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--sample", default="runs/external_cq/review_sample.csv")
    ap.add_argument("--out", default="runs/external_cq/review_sample.xlsx")
    args = ap.parse_args()

    with Path(args.sample).open(encoding="utf-8-sig", newline="") as fh:
        rows = list(csv.DictReader(fh))

    wb = Workbook()
    notes = wb.active
    notes.title = "说明"
    notes.column_dimensions["A"].width = 18
    notes.column_dimensions["B"].width = 110
    lines = [
        ("用途", f"外部 agent 涉诈候选的分层抽样复核表（{len(rows)} 条）。"),
        ("抽样设计", "按场景分层；n≤10 全看，否则 20%（最少 10、最多 20）。"
                     "已确认的 14 条 ab贷 不在本表。"),
        ("确认口径", "复核_is_fraud：1=4.2 涉诈；0=非 4.2（仅 4.1 或正常）。"
                     "复核_scene/subtype 按 spec 填。"),
        ("估噪与采纳", "复核完成后按场景计算 precision 与 Wilson 95% CI；"
                       "点估计≥0.90 且下界≥0.70 时，该场景剩余未抽样行自动采纳为正例；"
                       "否则保持待定，不进入正例/负例。"),
        ("不要用 probe 选标签", "probe_P涉诈 只用于排序参考；probe 是待评估模型，"
                                 "用它的判断挑正例会高估 recall。"),
        ("负类", "agent 正常/违规行已按负类处理；v2 重合核对中其 4.2 率仅 0.8%/0.1%。"),
    ]
    for i, (key, value) in enumerate(lines, start=1):
        notes.cell(row=i, column=1, value=key).font = Font(bold=True)
        notes.cell(row=i, column=2, value=value).alignment = WRAP
        notes.row_dimensions[i].height = 40

    ws = wb.create_sheet(f"抽样{len(rows)}")
    ws.append([c for c, _ in COLUMNS])
    for idx, (name, width) in enumerate(COLUMNS, start=1):
        cell = ws.cell(row=1, column=idx)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center",
                                   horizontal="center")
        cell.border = BORDER
        ws.column_dimensions[get_column_letter(idx)].width = width
    ws.row_dimensions[1].height = 30
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(COLUMNS))}{len(rows) + 1}"

    for n, r in enumerate(rows, start=1):
        ws.append([
            n, r["scene"], r["agent_res"], r["agent_conf"],
            float(r["probe_p"]) if r["probe_p"] else "",
            r["source_file"], r["source_date"], r["id"], safe(r["内容"]),
            "", "", "", "", "", "",
        ])
        line = ws.max_row
        ws.row_dimensions[line].height = 62
        for col, cell in enumerate(ws[line], start=1):
            cell.alignment = WRAP
            cell.border = BORDER
            if COLUMNS[col - 1][0] in MANUAL:
                cell.fill = MANUAL_FILL
            elif COLUMNS[col - 1][0] == "probe_P涉诈" and isinstance(cell.value, float):
                cell.number_format = "0.000"

    last = len(rows) + 1
    fraud_dv = DataValidation(type="list", formula1='"0,1"', allow_blank=True)
    ws.add_data_validation(fraud_dv)
    col = get_column_letter([c for c, _ in COLUMNS].index("复核_is_fraud") + 1)
    fraud_dv.add(f"{col}2:{col}{last}")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    wb.save(out)
    print(f"wrote {out} ({len(rows)} sample rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
