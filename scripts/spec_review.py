# 对比现有标签
# --------------------------------------------------------------------------- #
def current_label(row: dict) -> tuple[str, str, int]:
    return row["risk_level"], row["label_v2"], int(row["is_violation"] or 0)


def compare(row: dict, v: Verdict) -> tuple[str, str]:
    cur_risk, cur_label, cur_viol = current_label(row)
    cur_fraud = 1 if cur_label == "涉诈" else 0
    notes = []
    if cur_fraud != v.is_fraud:
        notes.append(f"涉诈判定不一致（现有:{cur_label} vs spec:{'涉诈' if v.is_fraud else '非涉诈'}）")
    elif v.is_fraud and row.get("proposed_scene_category") and row["proposed_scene_category"] != v.category:
        notes.append(f"涉诈类型不一致（现有:{row['proposed_scene_category']} vs spec:{v.category}）")
    elif LEVEL_ORDER.get(cur_risk, -1) != LEVEL_ORDER.get(v.risk, -2):
        notes.append(f"风险等级不一致（现有:{cur_risk} vs spec:{v.risk}）")
    status = "agree" if not notes else "disagree"
    if v.confidence == "低":
        status = "needs_human"
    return status, "；".join(notes) if notes else "等级与涉诈判定一致"


