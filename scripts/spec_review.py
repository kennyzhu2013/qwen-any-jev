def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--digest", action="store_true", help="输出分歧项证据摘要")
    ap.add_argument("--apply", action="store_true", help="应用裁定并输出最终结论 CSV")
    args = ap.parse_args()

    rows = list(csv.DictReader(open(QUEUE_CSV, encoding="utf-8-sig")))
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    verdicts = []
    for row in rows:
        v = review_one(row["content"])
        status, note = compare(row, v)
        verdicts.append((row, v, status, note))

    if args.digest:
        import collections
        stat = collections.Counter(s for _, _, s, _ in verdicts)
        print("分层统计:", dict(stat))
        lines = ["# 需人工裁定条目（分歧 / 存疑）", ""]
        for row, v, status, note in verdicts:
            if status == "agree":
                continue
            lines += [
                f"## {row['data_id']}  [{status}] {note}",
                f"- 现有：{row['label_v2']} / {row['risk_level']} / {row.get('scene_category','')}"
                f"（来源 {row['label_source']}）",
                f"- spec：{'涉诈·' + v.fraud if v.is_fraud else v.category} / {v.risk}",
            ]
            for h in v.hits[:5]:
                lines.append(f"  - [{h.scene}·{h.level}] {h.note}｜…{h.evidence}…")
            lines.append(f"- 原文前 260 字：{row['content'][:260]}")
            lines.append("")
        (OUT_DIR / "disagreements.md").write_text("\n".join(lines), encoding="utf-8")
        print(f" wrote {OUT_DIR/'disagreements.md'}")
        return 0

    with open(OUT_DIR / "verdicts.csv", "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.writer(fh)
        w.writerow(["data_id", "label_source", "现有_label", "现有_risk", "现有_category",
                    "spec_is_fraud", "spec_category", "spec_risk", "spec_subtype",
                    "status", "对比说明", "hits"])
        for row, v, status, note in verdicts:
            w.writerow([row["data_id"], row["label_source"], row["label_v2"], row["risk_level"],
                        row.get("scene_category", ""), v.is_fraud, v.category, v.risk, v.subtype,
                        status, note,
                        " || ".join(f"{h.scene}·{h.level}:{h.note}" for h in v.hits)][:12])

    if args.apply:
        with open(OUT_DIR / "final_conclusions.csv", "w", newline="", encoding="utf-8-sig") as fh:
            w = csv.writer(fh)
            w.writerow(["data_id", "人工复核_is_fraud", "人工复核_场景标签", "人工复核_风险等级",
                        "人工复核_判定说明", "结论来源", "原_label", "原_risk"])
            n_adj = 0
            for row, v, status, note in verdicts:
                adj = ADJUDICATIONS.get(row["data_id"])
                if adj:
                    isf, cat, risk, why = adj
                    src = "manual_adjudicated"
                    n_adj += 1
                elif row["data_id"] in ACCEPT_ENGINE:
                    isf, cat, risk = v.is_fraud, v.category, v.risk
                    why = "；".join(v.reasons[:3]) or "未命中违规/涉诈特征，按正常合规"
                    src = "manual_accepted_engine"
                    n_adj += 1
                else:
                    isf, cat, risk = v.is_fraud, v.category, v.risk
                    why = "；".join(v.reasons[:3]) or "未命中违规/涉诈特征，按正常合规"
                    src = "rule_engine" if status == "agree" else f"rule_engine[{status}待人工]"
                label = "涉诈" if isf else "非涉诈"
                w.writerow([row["data_id"], isf, cat, risk, f"{cat}：{why}", src,
                            row["label_v2"], row["risk_level"]])
        print(f" wrote final_conclusions.csv (adjudicated {n_adj}/{len(rows)})")

    import collections
    stat = collections.Counter(s for _, _, s, _ in verdicts)
    fr = collections.Counter(v.category for _, v, _, _ in verdicts if v.is_fraud)
    print("分层:", dict(stat), "| spec 涉诈命中:", dict(fr))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
