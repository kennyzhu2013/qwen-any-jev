@dataclass
class Hit:
    scene: str
    level: str          # 低风险/中风险/高风险 或 '涉诈'
    note: str
    evidence: str = ""
    category: str = ""  # 涉诈时的最终场景标签


@dataclass
class Verdict:
    fraud: str = ""            # 涉诈场景名（命中即非空）
    category: str = "正常"
    risk: str = "合规"
    subtype: str = ""
    is_fraud: int = 0
    hits: list = field(default_factory=list)
    confidence: str = "高"      # 高 / 低（低 => needs_human）
    reasons: list = field(default_factory=list)


def find(pattern: str | re.Pattern, text: str) -> re.Match | None:
    rx = re.compile(pattern) if isinstance(pattern, str) else pattern
    return rx.search(text)


def sentence_of(text: str, pos: int, width: int = 90) -> str:
    lo, hi = max(0, pos - 30), min(len(text), pos + width)
    return text[lo:hi].replace("\n", " ")


def eval_fraud(text: str) -> list[Hit]:
    hits: list[Hit] = []
    for scene, mode, note, pat in FRAUD_RULES:
        if mode == "any":
            m = find(pat, text)
            if m:
                hits.append(Hit(scene, "涉诈", note, sentence_of(text, m.start()), category=scene))
        else:  # cooccur2: 两个核心特征都命中
            ms = [find(p, text) for p in pat]
            if all(ms):
                ev = " … ".join(sentence_of(text, m.start(), 60) for m in ms)
                hits.append(Hit(scene, "涉诈", note, ev, category=scene))
    # 4.1.2 升级涉诈：贷款场景 + 引导/对接第三方（含主动加微后转交经理的实质）
    if not any(h.category == "引导贷款用户添加第三方微信" for h in hits):
        if find(LOAN_SCENE, text) and find(USER_ACTIVE_ADD, text) and find(THIRD_PARTY_ADD, text):
            m = find(USER_ACTIVE_ADD, text)
            hits.append(Hit("贷款相关", "涉诈", "贷款场景引导用户主动添加第三方/对接经理",
                            sentence_of(text, m.start()), category="引导贷款用户添加第三方微信"))
    # 芝麻分无银行渠道 → 手机租赁套路贷
    m = find(r"(芝麻信用|芝麻分).{0,15}(截图|多少|看一下|提供|分数)", text)
    if m and not re.search(r"(银行|持牌)", text):
        hits.append(Hit("手机租赁套路贷诈骗", "涉诈", "贷款推销中询问/索要芝麻分且无明确银行渠道",
                        sentence_of(text, m.start()), category="手机租赁套路贷诈骗"))
    return hits


def eval_violations(text: str) -> list[Hit]:
    hits: list[Hit] = []
    for scene, level, note, pat in VIOLATION_RULES:
        m = find(pat, text)
        if m:
            # 贷款相关·低风险规则需贷款语境（避免非贷款通话里的『保证金/包过』误触）；
            # 中/高风险（公积金提取、征信修复、债务优化等）行为本身即违规，不受语境门控限制
            if scene == "贷款相关" and level == "低风险" and not find(LOAN_SCENE, text) \
                    and not re.search(r"(度小满|安逸花|拍拍贷|分期|花呗|借呗|好分期|还呗|众安|信用飞|借条|京东金融|有钱花|宜享花|小花钱包|网贷)", text):
                continue
            # 外呼人员主动加用户微信＝合规（不分场景）：命中点之前已有外呼主动加微话术则豁免
            if note.startswith("引导用户主动添加个人微信"):
                m_ob = find(OUTBOUND_ACTIVE_ADD, text)
                if m_ob and m_ob.start() < m.start():
                    continue
            # 4.1.7 律师身份催收：仅在催收/逾期语境下算催收类行为
            if note.startswith("律所/律师身份催收") and not find(COLLECTION_SCENE, text):
                continue
            # 催收冒充公检法：排除正规调解/仲裁业务语境存疑时降置信（由 digest 人工裁定）
            hits.append(Hit(scene, level, note, sentence_of(text, m.start())))
    # 第三方添加微信（贷款场景低风险，归属贷款相关）
    m = find(THIRD_PARTY_ADD, text)
    if m and find(LOAN_SCENE, text):
        hits.append(Hit("贷款相关", "低风险", "第三方/经理将添加用户微信对接办理",
                        sentence_of(text, m.start())))
    return hits


def review_one(text: str) -> Verdict:
    v = Verdict()
    fraud_hits = eval_fraud(text)
    vio_hits = eval_violations(text)
    v.hits = fraud_hits + vio_hits

    if fraud_hits:
        chosen = sorted(fraud_hits, key=lambda h: FRAUD_PRIORITY.index(h.category))[0]
        v.fraud = chosen.category
        v.category = chosen.category
        v.risk = "高风险"
        v.is_fraud = 1
        v.subtype = chosen.note
        v.confidence = "高"
        # 单特征 any 型涉诈（荐股/退息/年报/ab贷关键词）语境弱时降置信
        if len(fraud_hits) == 1 and chosen.category in (
                "证券投资类", "网贷平台退息退费", "个体工商户年报补录收费"):
            v.confidence = "低"
        v.reasons.append(f"涉诈优先命中：{chosen.category}｜{chosen.note}")

    lvl = max((LEVEL_ORDER[h.level] for h in vio_hits), default=0)
    if not v.is_fraud:
        if lvl > 0:
            best = [h for h in vio_hits if LEVEL_ORDER[h.level] == lvl]
            v.category = best[0].scene
            v.risk = LEVEL_NAME[lvl]
            v.subtype = "；".join(dict.fromkeys(h.note for h in best))
            v.is_fraud = 0
        else:
            v.category, v.risk = "正常", "合规"
        v.reasons.extend(f"{h.scene}·{h.level}：{h.note}" for h in best[:4]) if lvl > 0 else None
    else:
        if lvl > 0:
            v.reasons.append(f"同时命中违规（{LEVEL_NAME[lvl]}），按就高不就低维持高风险")

    # 存疑信号：引流第三方在贷款场景外的归属、敏感信息组合、公检法疑似
    if find(DOC_NUMBER, text) and find(THIRD_PARTY_ADD, text) and v.risk == "合规":
        v.confidence = "低"
        v.reasons.append("存疑：通话中出现长数字串且存在第三方对接话术")
    return v


